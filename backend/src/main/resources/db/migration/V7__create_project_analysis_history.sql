CREATE TABLE project_analysis_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    report_json TEXT NOT NULL,
    analyzed_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_project_analysis_history_project
        FOREIGN KEY (project_id)
        REFERENCES projects (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_project_analysis_history_project_date
    ON project_analysis_history (
        project_id,
        analyzed_at DESC,
        id DESC
    );

INSERT INTO project_analysis_history (
    project_id,
    report_json,
    analyzed_at
)
SELECT
    project_id,
    report_json,
    analyzed_at
FROM project_analysis_reports;